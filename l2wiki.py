for monster_entry in tqdm(monsters, desc="Fetching monster data"):
    monster_id = monster_entry['id']
    if monster_id and monster_id in downloaded_ids:
        continue
    if monster_id:
        full_url = f"{base_url}{monster_id}"
        try:
            response = r.get(full_url)
            response.raise_for_status() # Raise an exception for bad status codes (4xx or 5xx)
            extracted_data = extract_monster_data(response.text)
            if extracted_data:
                if monster_id not in d_monsters:
                    d_monsters[monster_id] = extracted_data['monster']

                d_monsters[monster_id]['items'] = list()
                d_monsters[monster_id]['locations'] = list()
                d_monsters[monster_id]['skills'] = list()

                for item in extracted_data['items']:
                    if item['item_id'] not in d_items:
                        d_items[item['item_id']] = item
                    d_monsters[monster_id]['items'].append({
                            'item_id': item['item_id'],
                            'min': item['min'],
                            'max': item['max'],
                            'chance': item['chance'],
                            'spoil': item['spoil']
                        })

                for location in extracted_data['locations']:
                    if location['id'] not in d_locations:
                        d_locations[location['id']] = location
                    d_monsters[monster_id]['locations'].append(location['id'])

                for skill in extracted_data['skills']:
                    if skill['skill_id'] not in d_skills:
                        d_skills[skill['skill_id']] = skill
                    d_monsters[monster_id]['skills'].append({
                        'skill_id': skill['skill_id'],
                        'level': skill['level']
                        })

                downloaded_ids.add(monster_id)
            else:
                print(f"Could not extract data for monster ID: {monster_id}")
        except Exception as e:
            print(f"Error fetching data for monster ID {monster_id}: {e}")

