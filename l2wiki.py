import re

def extract_monster_data(html: str):
    def extract(pattern):
        m = re.search(pattern, html, re.S)
        return json.loads(m.group(1)) if m else None

    monster   = extract(r"var\s+monster\s*=\s*(\{[\s\S]*?\})\s*;")
    skills    = extract(r"var\s+skills\s*=\s*(\[[\s\S]*?\])\s*;")
    items     = extract(r"var\s+items\s*=\s*(\[[\s\S]*?\])\s*;")
    locations = extract(r"var\s+locations\s*=\s*(\[[\s\S]*?\])\s*;")

    return {
        "monster": monster,
        "skills": skills,
        "items": items,
        "locations": locations
    }

